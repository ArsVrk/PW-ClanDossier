-- PW Clan Dossier: isolated schema for a dedicated Supabase project.
-- Run only in the NEW project "PW Clan Dossier", never in PWResoCop Project.
create table if not exists public.players (
  wid bigint primary key,
  name text,
  class_id integer,
  class_name text,
  level integer,
  rebirth integer,
  first_seen text,
  last_seen text
);

create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  wid bigint not null,
  name text,
  captured_at text not null,
  equipment_ok integer,
  detailed_ok integer,
  error text,
  status_state text default 'UNKNOWN',
  status_count integer,
  status_ids_json text,
  status_records_json text,
  status_checked_at text,
  constraint scans_wid_captured_at_key unique (wid, captured_at)
);
create index if not exists scans_wid_captured_at_idx on public.scans (wid, captured_at desc);
create index if not exists scans_detailed_ok_idx on public.scans (detailed_ok, id desc);

create table if not exists public.stats (
  scan_id bigint primary key references public.scans(id) on delete cascade,
  json text,
  damage_rating integer,
  hp_rating integer,
  max_hp integer,
  max_mp integer,
  phys_min integer,
  phys_max integer,
  phys_def integer,
  attack_level integer,
  defense_level integer,
  critical integer
);

create table if not exists public.equipment (
  scan_id bigint not null references public.scans(id) on delete cascade,
  slot integer not null,
  template_id bigint,
  runtime_class integer,
  item_count integer,
  flags integer,
  refine integer,
  durability integer,
  max_durability integer,
  sockets_json text,
  properties_json text,
  primary key (scan_id, slot)
);

-- Persistent state that would otherwise be lost when a Render instance restarts.
create table if not exists public.app_settings (
  key text primary key,
  value_json text not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.item_metadata (
  item_id text primary key,
  metadata_json text not null,
  updated_at timestamptz not null default now()
);

-- The Python service uses its server-side DATABASE_URL and does not expose DB tables
-- directly through the Supabase Data API. Keep RLS enabled as defense in depth.
alter table public.players enable row level security;
alter table public.scans enable row level security;
alter table public.stats enable row level security;
alter table public.equipment enable row level security;
alter table public.app_settings enable row level security;
alter table public.item_metadata enable row level security;
